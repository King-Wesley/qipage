'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=__dirname;
const read=file=>fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n').trimEnd();
const expected='// Generated by build.cjs from style-config.js and ui.js.\n'+read('style-config.js')+'\n\n'+read('ui.js')+'\n';
const target=path.join(root,'app.js');
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==expected){console.error('app.js is out of date. Run npm run build.');process.exitCode=1;}
}else fs.writeFileSync(target,expected);
