'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=__dirname;
const runtime=fs.readFileSync(path.join(root,'style-config.js'),'utf8').replace(/\r\n/g,'\n').trimEnd();
const ui=fs.readFileSync(path.join(root,'ui.js'),'utf8').trimEnd();
const expected='// Generated by build.cjs from style-config.js and ui.js.\n'+runtime+'\n\n'+ui+'\n';
const target=path.join(root,'app.js');
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==expected){console.error('app.js is out of date. Run npm run build.');process.exitCode=1;}
}else fs.writeFileSync(target,expected);
